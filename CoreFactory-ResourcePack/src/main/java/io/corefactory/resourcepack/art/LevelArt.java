package io.corefactory.resourcepack.art;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.stream.Stream;

/**
 * The level textures of the lab machines. A lab machine has three levels: level I keeps its own model, and levels II and III
 * are the same machine with trim. Level II has gold trim along the edges of its front and top faces; level III has cyan trim
 * on the same edges and three small lamps on the front. The other sides are the level I sides.
 *
 * <p>Each level is a {@link MachineArt.Spec} with the id {@code ID_2} or {@code ID_3}, which the resource pack draws as
 * {@code machine/ID_2} or {@code machine/ID_3}. Its faces are the level I faces with the trim painted on. An animated face is
 * painted frame by frame from the same frames as the level I strip, and trimmed, so the level keeps its motion.
 * {@link #write} is called once by {@link ArtGenerator}.
 */
public final class LevelArt {

    /** The lab machines of processes.yml: the twelve drawn by {@link MachineArt} and the eight of {@link ProcessMachineArt}. */
    public static final List<String> LAB_MACHINES = List.of("crusher", "roaster", "separator", "purifier", "converter",
            "enrichment_cascade", "transmuter", "spectrometer", "particle_accelerator", "antimatter_condenser",
            "research_console", "crude_oil_refinery", "induction_furnace", "powder_mill", "cartridge_press",
            "bullet_swaging_machine", "ammunition_assembly", "metal_lathe", "component_assembly", "heavy_weapons_assembly");

    /** The levels that have a texture of their own: II and III. */
    public static final List<Integer> LEVELS = List.of(2, 3);

    /**
     * The inventory sprites of the module kits, machine_upgrade_2 and machine_upgrade_3: a module housing with a trim frame in the
     * level's colour and a row of lamps, one lit for level II and all three for level III.
     */
    public static final List<ComponentArt.Spec> SPRITES = List.of(
            new ComponentArt.Spec("machine_upgrade_2", "#5A6068", "#F2C230", module(1)),
            new ComponentArt.Spec("machine_upgrade_3", "#5A6068", "#3FE8FF", module(3)));

    private static final int GOLD = Color.hex("#F2C230");
    private static final int CYAN = Color.hex("#3FE8FF");
    /** The width of a trim line, in texture pixels: one model unit, a sixteenth of a block. */
    private static final int TRIM = 2;
    private static final int LAMP = 2;
    private static final String HEADER = "# Generated by io.corefactory.resourcepack.art.ArtGenerator. Change the painter, then run the generator.\n";

    /** An animated face of a lab machine: the side and the ticks each frame is shown. */
    private record Animation(MachineArt.Face face, int frametime) {
    }

    private LevelArt() {
    }

    /**
     * Writes the level II and III faces and their descriptors under {@code out}, in the layout {@link ArtGenerator} uses, and adds
     * the front and top faces of each to {@code tiles} for the contact sheet.
     *
     * @param out   the art directory
     * @param tiles the contact sheet's tiles, appended to
     */
    public static void write(Path out, List<BufferedImage> tiles) throws IOException {
        for (String id : LAB_MACHINES) {
            MachineArt.Spec base = base(id);
            Optional<Animation> animation = animation(id);
            for (int level : LEVELS) {
                MachineArt.Spec spec = levelSpec(base, level);
                for (MachineArt.Face face : MachineArt.Face.values()) {
                    boolean animated = animation.filter(a -> a.face() == face).isPresent();
                    BufferedImage first = still(spec, face);
                    writePng(animated ? strip(base, face, level) : first, out.resolve(texture(spec, face)));
                    if (face == MachineArt.Face.NORTH || face == MachineArt.Face.UP) {
                        tiles.add(first);
                    }
                }
                writeText(out.resolve("specs/machine/" + spec.id() + ".yml"), descriptor(spec, animation));
            }
        }
    }

    /**
     * The level spec of a lab machine: the same silhouette and colours as the level I spec, with the id of the level, and faces that
     * paint the level I face with the level's trim on it.
     *
     * @param base  the level I spec, from {@link #base}
     * @param level the level, {@code 2} or {@code 3}
     */
    public static MachineArt.Spec levelSpec(MachineArt.Spec base, int level) {
        checkLevel(level);
        Map<MachineArt.Face, ComponentArt.Painter> faces = new EnumMap<>(MachineArt.Face.class);
        for (MachineArt.Face face : MachineArt.Face.values()) {
            faces.put(face, (c, colour, accent, seed) -> {
                MachineArt.paintFace(c, base, face);
                trim(c, base, face, level);
            });
        }
        return new MachineArt.Spec(base.id() + "_" + level, base.base(), base.accent(), base.boxes(),
                faces.get(MachineArt.Face.NORTH), faces);
    }

    /** The level I spec of a lab machine: from {@link MachineArt}, or from {@link ProcessMachineArt} for the process machines. */
    public static MachineArt.Spec base(String id) {
        return Stream.concat(MachineArt.ALL.stream(), ProcessMachineArt.ALL.stream())
                .filter(spec -> spec.id().equals(id))
                .findFirst()
                .orElseThrow(() -> new IllegalArgumentException("No art for lab machine " + id));
    }

    /**
     * Paints the trim of a level on one face of a level I machine. Levels II and III trim the north (front) face along the edges of
     * the boxes nearest the viewer, and the up (top) face along the edges of the boxes that reach the top. Level III adds three lamps
     * on the front. The other faces are not trimmed.
     */
    static void trim(Canvas c, MachineArt.Spec base, MachineArt.Face face, int level) {
        int colour = level == 2 ? GOLD : CYAN;
        if (face == MachineArt.Face.NORTH) {
            List<MachineArt.Box> front = frontmost(base.boxes());
            for (MachineArt.Box box : front) {
                c.paint(outline(2 * box.x0(), 32 - 2 * box.y1(), 2 * box.x1(), 32 - 2 * box.y0()), colour);
            }
            if (level == 3 && !front.isEmpty()) {
                lamps(c, front.get(0), colour);
            }
        } else if (face == MachineArt.Face.UP) {
            for (MachineArt.Box box : topmost(base.boxes())) {
                c.paint(outline(2 * box.x0(), 2 * box.z0(), 2 * box.x1(), 2 * box.z1()), colour);
            }
        }
    }

    /** A strip of the trimmed animated face: each frame is the level I frame with the trim, halved as {@link MachineAnimation} does. */
    static BufferedImage strip(MachineArt.Spec base, MachineArt.Face face, int level) {
        int size = MachineAnimation.FRAME;
        BufferedImage strip = new BufferedImage(size, size * MachineAnimation.FRAMES, BufferedImage.TYPE_INT_ARGB);
        for (int frame = 0; frame < MachineAnimation.FRAMES; frame++) {
            Canvas canvas = new Canvas();
            MachineArt.paintCasing(canvas, base, face);
            paintAnimatedFrame(canvas, base, frame);
            trim(canvas, base, face, level);
            strip.setRGB(0, frame * size, size, size, halve(canvas), 0, size);
        }
        return strip;
    }

    /** The first frame of a face as a full canvas image: the level I face with the trim on it. */
    private static BufferedImage still(MachineArt.Spec spec, MachineArt.Face face) {
        Canvas canvas = new Canvas();
        MachineArt.paintFace(canvas, spec, face);
        return canvas.toImage();
    }

    /** One frame of a lab machine's animated face, over the casing already on the canvas. */
    private static void paintAnimatedFrame(Canvas canvas, MachineArt.Spec base, int frame) {
        if (MachineAnimation.clip(base.id()).isPresent()) {
            MachineAnimation.paintFrame(canvas, base, frame);
        } else {
            ProcessMachineArt.paintFrame(canvas, base.id(), Color.hex(base.base()), Color.hex(base.accent()), frame);
        }
    }

    /** The animated face of a lab machine, if it has one. */
    private static Optional<Animation> animation(String id) {
        Optional<MachineAnimation.Clip> clip = MachineAnimation.clip(id);
        if (clip.isPresent()) {
            return Optional.of(new Animation(clip.get().face(), clip.get().frametime()));
        }
        return ProcessMachineArt.clip(id).map(c -> new Animation(c.face(), c.frametime()));
    }

    /** The boxes whose front is nearest the viewer: the ones at the smallest z. */
    private static List<MachineArt.Box> frontmost(List<MachineArt.Box> boxes) {
        double nearest = boxes.stream().mapToDouble(MachineArt.Box::z0).min().orElse(0);
        return boxes.stream().filter(box -> box.z0() == nearest).toList();
    }

    /** The boxes that reach the top of the silhouette: the ones at the largest y. */
    private static List<MachineArt.Box> topmost(List<MachineArt.Box> boxes) {
        double highest = boxes.stream().mapToDouble(MachineArt.Box::y1).max().orElse(0);
        return boxes.stream().filter(box -> box.y1() == highest).toList();
    }

    /** The inventory painter of a module kit with {@code lit} of its three lamps lit. */
    private static ComponentArt.Painter module(int lit) {
        return (c, base, accent, seed) -> {
            Area housing = Area.roundRect(7, 4, 25, 28, 3);
            Sprite.body(c, housing, base, seed);
            c.paint(housing.minus(Area.roundRect(9, 6, 23, 26, 2)), accent);
            c.paint(Area.rect(10, 10, 22, 16), Color.hex("#1A1A1E"));
            for (int k = 0; k < 3; k++) {
                double x = 12 + 4 * k;
                c.paint(Area.disc(x, 13, 1.3), k < lit ? accent : Color.hex("#3A3F48"));
            }
            c.paint(Area.rect(10, 20, 22, 23), Color.scale(base, 0.5));
        };
    }

    /** A rectangle's outline, {@link #TRIM} pixels wide, inside the rectangle. */
    private static Area outline(double x0, double y0, double x1, double y1) {
        return Area.rect(x0, y0, x1, y1).minus(Area.rect(x0 + TRIM, y0 + TRIM, x1 - TRIM, y1 - TRIM));
    }

    /** Three small lamps in a row across the lower middle of a front box. */
    private static void lamps(Canvas c, MachineArt.Box box, int colour) {
        double centre = (2 * box.x0() + 2 * box.x1()) / 2;
        double bottom = 32 - 2 * box.y0();
        for (int k = 0; k < 3; k++) {
            double x = centre - 4 + 3 * k;
            c.paint(Area.rect(x, bottom - 6, x + LAMP, bottom - 4), colour);
        }
    }

    private static String texture(MachineArt.Spec spec, MachineArt.Face face) {
        return "textures/block/machine/" + spec.id() + "/" + face.key() + ".png";
    }

    /** A machine descriptor in the format of {@link ArtGenerator}: six face textures, the animation, and the cuboids. */
    private static String descriptor(MachineArt.Spec spec, Optional<Animation> animation) {
        StringBuilder text = new StringBuilder(HEADER);
        text.append("id: ").append(spec.id()).append("\n");
        text.append("kind: machine\n");
        text.append("model: machine\n");
        text.append("palette:\n");
        text.append("  base: \"").append(spec.base()).append("\"\n");
        text.append("  accent: \"").append(spec.accent()).append("\"\n");
        text.append("textures:\n");
        for (MachineArt.Face face : MachineArt.Face.values()) {
            text.append("  ").append(face.key()).append(": ").append(texture(spec, face)).append("\n");
        }
        animation.ifPresent(a -> text.append("animation:\n")
                .append("  frames: ").append(MachineAnimation.FRAMES).append("\n")
                .append("  frametime: ").append(a.frametime()).append("\n")
                .append("  textures: [").append(a.face().key()).append("]\n"));
        text.append("elements:\n");
        for (MachineArt.Box box : spec.boxes()) {
            text.append("  - from: [").append(num(box.x0())).append(", ").append(num(box.y0())).append(", ")
                    .append(num(box.z0())).append("]\n");
            text.append("    to: [").append(num(box.x1())).append(", ").append(num(box.y1())).append(", ")
                    .append(num(box.z1())).append("]\n");
        }
        return text.toString();
    }

    /** A coordinate as YAML writes it: {@code 4} for a whole number, {@code 9.5} otherwise. */
    private static String num(double value) {
        return value == Math.rint(value) ? Long.toString((long) value) : Double.toString(value);
    }

    private static int[] halve(Canvas canvas) {
        int size = MachineAnimation.FRAME;
        int[] pixels = new int[size * size];
        for (int y = 0; y < size; y++) {
            for (int x = 0; x < size; x++) {
                int alpha = 0;
                int red = 0;
                int green = 0;
                int blue = 0;
                for (int dy = 0; dy < 2; dy++) {
                    for (int dx = 0; dx < 2; dx++) {
                        int p = canvas.get(2 * x + dx, 2 * y + dy);
                        alpha += Color.alpha(p);
                        red += Color.red(p);
                        green += Color.green(p);
                        blue += Color.blue(p);
                    }
                }
                pixels[y * size + x] = Color.argb(alpha / 4, red / 4, green / 4, blue / 4);
            }
        }
        return pixels;
    }

    private static void checkLevel(int level) {
        if (!LEVELS.contains(level)) {
            throw new IllegalArgumentException("Level textures exist for levels 2 and 3, not " + level);
        }
    }

    private static void writePng(BufferedImage image, Path file) throws IOException {
        Files.createDirectories(file.getParent());
        ImageIO.write(image, "png", file.toFile());
    }

    private static void writeText(Path file, String text) {
        try {
            Files.createDirectories(file.getParent());
            Files.writeString(file, text, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
